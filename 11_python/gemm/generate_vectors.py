#!/usr/bin/env python3
"""Generate tiled FC parameters and bit-exact standalone GEMM vectors.

This script intentionally reads the deployed TXT parameters rather than loading
params.pkl. It models the current project's binary Conv/ReLU/Pool front end and
HWC pool order, then generates signed integer golden data for the shared GEMM.
"""

import argparse
import hashlib
import json
import math
import re
from pathlib import Path

import numpy as np

POOL_SCALE = 97.625622
PE_N = 8
REQUANT_SHIFT = 31


def parse_params(path):
    text = path.read_text(encoding="utf-8")
    values = re.findall(r"=\s*([-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?)", text)
    return np.asarray(values, dtype=np.float64)


def write_hex(path, values, width):
    digits = (width + 3) // 4
    mask = (1 << width) - 1
    with path.open("w", encoding="ascii", newline="\n") as f:
        for value in np.asarray(values).reshape(-1):
            f.write(f"{int(value) & mask:0{digits}X}\n")


def pack_tiled_weights(weights, k_size, n_size):
    """Pack [N][K] int8 weights as [n_tile][k][lane], lane 0 in bits 7:0."""
    words = []
    for n_tile in range((n_size + PE_N - 1) // PE_N):
        for k in range(k_size):
            word = 0
            for lane in range(PE_N):
                n = n_tile * PE_N + lane
                value = int(weights[n, k]) if n < n_size else 0
                word |= (value & 0xFF) << (lane * 8)
            words.append(word)
    return np.asarray(words, dtype=object)


def tiled_golden(weights, activation):
    return np.asarray(activation, dtype=np.int64) @ np.asarray(weights, dtype=np.int64).T


def write_le64(path, values):
    values = np.asarray(values, dtype=object).reshape(-1)
    with path.open("wb") as f:
        for value in values:
            f.write((int(value) & 0xFFFFFFFFFFFFFFFF).to_bytes(8, "little"))
    payload = path.read_bytes()
    return {
        "file": path.name,
        "words": int(values.size),
        "bytes": len(payload),
        "sha256": hashlib.sha256(payload).hexdigest(),
    }


def write_c_header(path, sections):
    with path.open("w", encoding="ascii", newline="\n") as f:
        f.write("/* Generated by 11_python/gemm/generate_vectors.py. */\n")
        f.write("#ifndef GEMM_PARAMS_H\n#define GEMM_PARAMS_H\n\n#include <stdint.h>\n\n")
        for name, values in sections:
            flat = np.asarray(values, dtype=object).reshape(-1)
            f.write(f"static const uint64_t {name}[{flat.size}] ")
            f.write("__attribute__((aligned(64))) = {\n")
            for start in range(0, flat.size, 4):
                words = ", ".join(
                    f"UINT64_C(0x{int(value) & 0xFFFFFFFFFFFFFFFF:016X})"
                    for value in flat[start:start + 4]
                )
                f.write(f"    {words},\n")
            f.write("};\n\n")
        f.write("#endif\n")


def write_ddr_outputs(out, c_header, sections):
    ddr_dir = out / "ddr"
    ddr_dir.mkdir(parents=True, exist_ok=True)
    manifest = {}
    for name, values in sections:
        manifest[name] = write_le64(ddr_dir / f"{name}.bin", values)
    expected_bytes = {
        "gemm_fc1_bias_words": 800,
        "gemm_fc1_weight_words": 449280,
        "gemm_fc2_bias_words": 80,
        "gemm_fc2_weight_words": 1600,
    }
    for name, expected in expected_bytes.items():
        if manifest[name]["bytes"] != expected:
            raise ValueError(f"{name} DDR size mismatch")
    (ddr_dir / "manifest.json").write_text(
        json.dumps(manifest, indent=2) + "\n", encoding="ascii"
    )
    if c_header is not None:
        c_header.parent.mkdir(parents=True, exist_ok=True)
        write_c_header(c_header, sections)


def round_shift_signed(values, shift):
    """Round-to-nearest, ties away from zero, followed by arithmetic shift."""
    values = np.asarray(values, dtype=np.int64)
    magnitude = np.abs(values)
    rounded = (magnitude + (1 << (shift - 1))) >> shift
    return np.where(values < 0, -rounded, rounded)


def current_pool_golden(conv_w, conv_b, image):
    binary = (image > 0).astype(np.int64).reshape(28, 28)
    windows = np.lib.stride_tricks.sliding_window_view(binary, (5, 5))
    conv = np.zeros((30, 24, 24), dtype=np.int64)
    for channel in range(30):
        conv[channel] = np.einsum(
            "yxij,ij->yx", windows, conv_w[channel], optimize=True
        ) + conv_b[channel]
    conv = np.maximum(conv, 0)
    pool = conv.reshape(30, 12, 2, 12, 2).max(axis=(2, 4))
    pool_hwc = np.transpose(pool, (1, 2, 0)).reshape(4320)
    if np.max(np.abs(pool_hwc)) > 32767:
        raise ValueError("Pool golden exceeds INT16")
    return binary, pool_hwc


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--project-root", type=Path, required=True)
    parser.add_argument("--reference-dir", type=Path, required=True)
    parser.add_argument("--out-dir", type=Path, required=True)
    parser.add_argument("--c-header", type=Path)
    parser.add_argument("--mnist-offset", type=int, default=10)
    args = parser.parse_args()

    param_dir = args.project_root / "10_cnn"
    out = args.out_dir
    out.mkdir(parents=True, exist_ok=True)

    conv_w_float = parse_params(param_dir / "Conv_W.txt").reshape(30, 5, 5)
    conv_b_float = parse_params(param_dir / "Conv_B.txt")
    w1_float = parse_params(param_dir / "Affine1_W.txt").reshape(100, 4320)
    b1_float = parse_params(param_dir / "Affine1_B.txt")
    w2_float = parse_params(param_dir / "Affine2_W.txt").reshape(10, 100)
    b2_float = parse_params(param_dir / "Affine2_B.txt")

    conv_w = np.clip(np.rint(conv_w_float * POOL_SCALE), -128, 127).astype(np.int64)
    conv_b = np.clip(np.rint(conv_b_float * POOL_SCALE), -32768, 32767).astype(np.int64)

    image_path = args.reference_dir / "t10k-images.idx3-ubyte"
    label_path = args.reference_dir / "t10k-labels.idx1-ubyte"
    with image_path.open("rb") as f:
        f.seek(16 + args.mnist_offset * 784)
        image = np.frombuffer(f.read(784), dtype=np.uint8)
    with label_path.open("rb") as f:
        f.seek(8 + args.mnist_offset)
        label = f.read(1)[0]
    if image.size != 784:
        raise ValueError("Unable to read requested MNIST image")

    binary, pool_hwc = current_pool_golden(conv_w, conv_b, image)

    w1_scale = 127.0 / np.max(np.abs(w1_float))
    w2_scale = 127.0 / np.max(np.abs(w2_float))
    qw1 = np.clip(np.rint(w1_float * w1_scale), -128, 127).astype(np.int64)
    qw2 = np.clip(np.rint(w2_float * w2_scale), -128, 127).astype(np.int64)

    # Deployed pool order is HWC, while exported FC1 weights are CHW.
    qw1_hwc = np.transpose(qw1.reshape(100, 30, 12, 12), (0, 2, 3, 1)).reshape(100, 4320)
    w1_hwc_float = np.transpose(w1_float.reshape(100, 30, 12, 12), (0, 2, 3, 1)).reshape(100, 4320)

    fc1_raw = tiled_golden(qw1_hwc, pool_hwc)
    fc1_bias_acc = np.rint(b1_float * POOL_SCALE * w1_scale).astype(np.int64)
    fc1_pre = fc1_raw + fc1_bias_acc

    fc1_float = (pool_hwc.astype(np.float64) / POOL_SCALE) @ w1_hwc_float.T + b1_float
    max_fc1 = max(float(np.max(np.abs(fc1_float))), 1.0e-12)
    fc1_act_scale = float(2 ** math.floor(math.log2(32767.0 / (1.5 * max_fc1))))
    fc1_act_scale = min(max(fc1_act_scale, 1.0), float(2 ** 20))

    requant_factor = fc1_act_scale / (POOL_SCALE * w1_scale)
    requant_multiplier = int(round(requant_factor * (1 << REQUANT_SHIFT)))
    if not 0 < requant_multiplier < (1 << 31):
        raise ValueError("Requant multiplier does not fit signed 32-bit")

    fc1_scaled = round_shift_signed(fc1_pre * requant_multiplier, REQUANT_SHIFT)
    fc1_post = np.clip(fc1_scaled, 0, 32767).astype(np.int64)

    fc2_raw = tiled_golden(qw2, fc1_post)
    fc2_bias_acc = np.rint(b2_float * fc1_act_scale * w2_scale).astype(np.int64)
    fc2_logits = fc2_raw + fc2_bias_acc
    digit = int(np.argmax(fc2_logits))

    fc2_float = np.maximum(fc1_float, 0) @ w2_float.T + b2_float
    float_digit = int(np.argmax(fc2_float))

    # Small directed case: signed activations/weights, two output tiles, short PP tile.
    rng = np.random.default_rng(20261026)
    small_k, small_n = 17, 10
    small_act = rng.integers(-16, 17, size=small_k, dtype=np.int64)
    small_w = rng.integers(-8, 9, size=(small_n, small_k), dtype=np.int64)
    small_raw = tiled_golden(small_w, small_act)

    write_hex(out / "small_act.hex", small_act, 16)
    write_hex(out / "small_w.hex", pack_tiled_weights(small_w, small_k, small_n), 64)
    write_hex(out / "small_raw_golden.hex", small_raw, 40)

    fc1_w_tiled = pack_tiled_weights(qw1_hwc, 4320, 100)
    fc2_w_tiled = pack_tiled_weights(qw2, 100, 10)
    write_hex(out / "pool_hwc.hex", pool_hwc, 16)
    write_hex(out / "fc1_w_tiled.hex", fc1_w_tiled, 64)
    write_hex(out / "fc1_raw_golden.hex", fc1_raw, 40)
    write_hex(out / "fc1_bias_acc.hex", fc1_bias_acc, 40)
    write_hex(out / "fc1_pre_golden.hex", fc1_pre, 40)
    write_hex(out / "fc1_post_golden.hex", fc1_post, 16)

    write_hex(out / "fc1_act.hex", fc1_post, 16)
    write_hex(out / "fc2_w_tiled.hex", fc2_w_tiled, 64)
    write_hex(out / "fc2_raw_golden.hex", fc2_raw, 40)
    write_hex(out / "fc2_bias_acc.hex", fc2_bias_acc, 40)
    write_hex(out / "fc2_logits_golden.hex", fc2_logits, 40)
    write_hex(out / "binary_input.hex", binary.reshape(-1), 1)

    write_ddr_outputs(out, args.c_header, (
        ("gemm_fc1_bias_words", fc1_bias_acc),
        ("gemm_fc1_weight_words", fc1_w_tiled),
        ("gemm_fc2_bias_words", fc2_bias_acc),
        ("gemm_fc2_weight_words", fc2_w_tiled),
    ))

    config = {
        "mnist_offset": args.mnist_offset,
        "mnist_label": int(label),
        "pool_scale": POOL_SCALE,
        "pool_order": "HWC: y*360+x*30+c",
        "fc1_weight_scale": w1_scale,
        "fc2_weight_scale": w2_scale,
        "fc1_activation_scale": fc1_act_scale,
        "fc1_requant_multiplier": requant_multiplier,
        "fc1_requant_shift": REQUANT_SHIFT,
        "rounding": "nearest, ties away from zero",
        "small": {"k": small_k, "n": small_n, "weight_words": small_k * 2},
        "fc1": {"k": 4320, "n": 100, "weight_words": 4320 * 13},
        "fc2": {"k": 100, "n": 10, "weight_words": 100 * 2},
        "float_digit": float_digit,
        "fixed_digit": digit,
        "fc1_float_max_abs": max_fc1,
        "fc2_logits": [int(v) for v in fc2_logits],
    }
    (out / "quant_config.json").write_text(
        json.dumps(config, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )

    print(json.dumps(config, indent=2, ensure_ascii=False))
    if float_digit != digit:
        print("WARNING: fixed-point digit differs from floating-point reference")


if __name__ == "__main__":
    main()
